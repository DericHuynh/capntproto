impl<A> Builder<A>
where
    A: Allocator,
{
    pub fn new(allocator: A) -> Self {
        Self {
            arena: BuilderArenaImpl::new(allocator),
        }
    }

    /// Restrict this owning builder to a pointer selected from its root.
    ///
    /// The selector must return an unimbued pointer from this message. A pointer
    /// from another arena is rejected, even if it has a sufficiently long lifetime.
    pub fn select(
        mut self,
        select: impl for<'a> FnOnce(any_pointer::Builder<'a>) -> Result<any_pointer::Builder<'a>>,
    ) -> Result<SelectedBuilder<A>> {
        let arena = core::ptr::from_ref(&self.arena).cast::<()>();
        let (segment, offset) = select(self.get_root_internal())?
            .builder
            .owned_location(arena)?;
        Ok(SelectedBuilder {
            message: self,
            segment,
            offset,
        })
    }

    /// Select an existing or newly initialized struct for repeated mutation.
    /// The selector must return an unimbued struct from this message. On error
    /// the message is returned, including any edits made by the selector.
    // Returning the allocator's owner intact must also work without a heap.
    #[allow(clippy::result_large_err)]
    pub fn try_select_struct(
        mut self,
        select: impl for<'a> FnOnce(any_pointer::Builder<'a>) -> Result<crate::any_struct::Builder<'a>>,
    ) -> core::result::Result<SelectedStructBuilder<A>, (Self, Error)> {
        let arena = core::ptr::from_ref(&self.arena).cast::<()>();
        let result = select(self.get_root_internal())
            .and_then(|root| layout::CachedStructRoot::from_builder(root.builder, arena));
        match result {
            Ok(root) => Ok(SelectedStructBuilder {
                message: self,
                root,
            }),
            Err(error) => Err((self, error)),
        }
    }

    fn get_root_internal(&mut self) -> any_pointer::Builder<'_> {
        if self.arena.is_empty() {
            self.arena
                .allocate_segment(1)
                .expect("allocate root pointer");
            self.arena.allocate(0, 1).expect("allocate root pointer");
        }
        let (seg_start, _seg_len) = self.arena.get_segment_mut(0);
        let location: *mut u8 = seg_start;
        let Self { arena } = self;

        any_pointer::Builder::new(layout::PointerBuilder::get_root(arena, 0, location))
    }

    /// Initializes the root as a value of the given type.
    pub fn init_root<'a, T: FromPointerBuilder<'a>>(&'a mut self) -> T {
        let root = self.get_root_internal();
        root.init_as()
    }

    /// Initializes the root as a value of the given list type, with the given length.
    pub fn initn_root<'a, T: FromPointerBuilder<'a>>(&'a mut self, length: u32) -> T {
        let root = self.get_root_internal();
        root.initn_as(length)
    }

    /// Gets the root, interpreting it as the given type.
    pub fn get_root<'a, T: FromPointerBuilder<'a>>(&'a mut self) -> Result<T> {
        let root = self.get_root_internal();
        root.get_as()
    }

    pub fn get_root_as_reader<'a, T: FromPointerReader<'a>>(&'a self) -> Result<T> {
        if self.arena.is_empty() {
            any_pointer::Reader::new(layout::PointerReader::new_default()).get_as()
        } else {
            let (segment_start, _segment_len) = self.arena.get_segment(0)?;
            let pointer_reader = unsafe {
                layout::PointerReader::get_root(
                    self.arena.as_reader(),
                    0,
                    segment_start,
                    0x7fffffff,
                )
            }?;
            let root = any_pointer::Reader::new(pointer_reader);
            root.get_as()
        }
    }

    /// Sets the root to a deep copy of the given value.
    pub fn set_root<T: Owned>(&mut self, value: impl SetterInput<T>) -> Result<()> {
        let mut root = self.get_root_internal();
        root.set_as(value)
    }

    /// Sets the root to a canonicalized version of `value`. If this was the first action taken
    /// on this `Builder`, then a subsequent call to `get_segments_for_output()` should return
    /// a single segment, containing the full canonicalized message.
    pub fn set_root_canonical<T: Owned>(&mut self, value: impl SetterInput<T>) -> Result<()> {
        if self.arena.is_empty() {
            self.arena
                .allocate_segment(1)
                .expect("allocate root pointer");
            self.arena.allocate(0, 1).expect("allocate root pointer");
        }
        let (seg_start, _seg_len) = self.arena.get_segment_mut(0);
        let pointer = layout::PointerBuilder::get_root(&mut self.arena, 0, seg_start);
        SetterInput::set_pointer_builder(pointer, value, true)?;
        assert_eq!(self.get_segments_for_output().len(), 1);
        Ok(())
    }

    pub fn get_segments_for_output(&self) -> OutputSegments<'_> {
        self.arena.get_segments_for_output()
    }

    /// Total allocator-reported segment capacity in bytes, including unused
    /// words. Returns None on overflow or when an externally borrowed range
    /// cannot reveal its owner's complete capacity. This excludes bounded arena
    /// metadata and is useful when retaining segments in a byte-budgeted queue.
    pub fn retained_segment_bytes(&self) -> Option<usize> {
        self.arena.retained_segment_bytes()
    }

    pub fn into_reader(self) -> Reader<Self> {
        Reader::new(
            self,
            ReaderOptions {
                traversal_limit_in_words: None,
                nesting_limit: i32::MAX,
            },
        )
    }

    pub fn into_typed<T: Owned>(self) -> TypedBuilder<T, A> {
        TypedBuilder::new(self)
    }

    /// Retrieves the underlying `Allocator`, deallocating all currently-allocated
    /// segments.
    pub fn into_allocator(self) -> A {
        self.arena.into_allocator()
    }

    pub fn size_in_words(&self) -> usize {
        self.arena.size_in_words()
    }
}


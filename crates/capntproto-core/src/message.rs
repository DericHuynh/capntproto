/// Options controlling how data is read.
#[derive(Clone, Copy, Debug)]
pub struct ReaderOptions {
    /// Limits how many total (8-byte) words of data are allowed to be traversed. Traversal is counted
    /// when a new struct or list builder is obtained, e.g. from a get() accessor. This means that
    /// calling the getter for the same sub-struct multiple times will cause it to be double-counted.
    /// Once the traversal limit is reached, an error will be reported.
    ///
    /// This limit exists for security reasons. It is possible for an attacker to construct a message
    /// in which multiple pointers point at the same location. This is technically invalid, but hard
    /// to detect. Using such a message, an attacker could cause a message which is small on the wire
    /// to appear much larger when actually traversed, possibly exhausting server resources leading to
    /// denial-of-service.
    ///
    /// It makes sense to set a traversal limit that is much larger than the underlying message.
    /// Together with sensible coding practices (e.g. trying to avoid calling sub-object getters
    /// multiple times, which is expensive anyway), this should provide adequate protection without
    /// inconvenience.
    ///
    /// A traversal limit of `None` means that no limit is enforced.
    pub traversal_limit_in_words: Option<usize>,

    /// Limits how deeply nested a message structure can be, e.g. structs containing other structs or
    /// lists of structs.
    ///
    /// Like the traversal limit, this limit exists for security reasons. Since it is common to use
    /// recursive code to traverse recursive data structures, an attacker could easily cause a stack
    /// overflow by sending a very-deeply-nested (or even cyclic) message, without the message even
    /// being very large. The default limit of 64 is probably low enough to prevent any chance of
    /// stack overflow, yet high enough that it is never a problem in practice.
    pub nesting_limit: i32,
}

#[cfg(not(target_pointer_width = "16"))]
pub const DEFAULT_READER_OPTIONS: ReaderOptions = ReaderOptions {
    traversal_limit_in_words: Some(8 * 1024 * 1024),
    nesting_limit: 64,
};

#[cfg(target_pointer_width = "16")]
pub const DEFAULT_READER_OPTIONS: ReaderOptions = ReaderOptions {
    traversal_limit_in_words: Some(8 * 1024),
    nesting_limit: 64,
};

impl Default for ReaderOptions {
    fn default() -> Self {
        DEFAULT_READER_OPTIONS
    }
}

impl ReaderOptions {
    pub const fn new() -> Self {
        DEFAULT_READER_OPTIONS
    }

    pub fn nesting_limit(&mut self, value: i32) -> &mut Self {
        self.nesting_limit = value;
        self
    }

    pub fn traversal_limit_in_words(&mut self, value: Option<usize>) -> &mut Self {
        self.traversal_limit_in_words = value;
        self
    }
}

/// An object that manages the buffers underlying a Cap'n Proto message reader.
pub trait ReaderSegments {
    /// Gets the segment with index `idx`. Returns `None` if `idx` is out of range.
    ///
    /// The segment must be 8-byte aligned or the "unaligned" feature must
    /// be enabled in the capnp crate. (Otherwise reading the segment will return an error.)
    ///
    /// The returned slice is required to point to memory that remains valid until the ReaderSegments
    /// object is dropped. In safe Rust, it should not be possible to violate this requirement.
    fn get_segment(&self, idx: u32) -> Option<&[u8]>;

    /// Gets the number of segments.
    fn len(&self) -> usize {
        for i in 0u32.. {
            if self.get_segment(i).is_none() {
                return i as usize;
            }
        }
        unreachable!()
    }

    fn is_empty(&self) -> bool {
        self.len() == 0
    }
}

/// Allows stacking of references to a `ReaderSegments`.
///
/// This is especially useful with the implementation for slices, as it allows treating
/// `&[&[u8]]` as `ReaderSegments`, e.g., to construct a `Reader`:
/// ```
/// # use capnp::message::ReaderSegments;
/// use capnp::message::Reader;
/// let slice_of_slices: &[&[u8]] = &[&*b"some data", &*b"more data"];
/// let _ = Reader::new(slice_of_slices, Default::default());
/// ```
impl<S> ReaderSegments for &S
where
    S: ReaderSegments + ?Sized,
{
    fn get_segment(&self, idx: u32) -> Option<&[u8]> {
        (**self).get_segment(idx)
    }

    fn len(&self) -> usize {
        (**self).len()
    }

    fn is_empty(&self) -> bool {
        (**self).is_empty()
    }
}

/// An array of segments.
pub struct SegmentArray<'a> {
    segments: &'a [&'a [u8]],
}

impl<'a> SegmentArray<'a> {
    pub fn new(segments: &'a [&'a [u8]]) -> SegmentArray<'a> {
        SegmentArray { segments }
    }
}

impl ReaderSegments for SegmentArray<'_> {
    fn get_segment(&self, id: u32) -> Option<&[u8]> {
        self.segments.get(id as usize).copied()
    }

    fn len(&self) -> usize {
        self.segments.len()
    }
}

impl<I> ReaderSegments for [I]
where
    I: AsRef<[u8]>,
{
    fn get_segment(&self, id: u32) -> Option<&[u8]> {
        self.get(id as usize).map(|i| i.as_ref())
    }

    fn len(&self) -> usize {
        self.len()
    }

    fn is_empty(&self) -> bool {
        self.is_empty()
    }
}

#[cfg(feature = "alloc")]
impl<I> ReaderSegments for alloc::vec::Vec<I>
where
    I: AsRef<[u8]>,
{
    fn get_segment(&self, id: u32) -> Option<&[u8]> {
        self.get(id as usize).map(|i| i.as_ref())
    }

    fn len(&self) -> usize {
        self.len()
    }

    fn is_empty(&self) -> bool {
        self.is_empty()
    }
}

/// A container used to read a message.
pub struct Reader<S, B = ReadBudget>
where
    S: ReaderSegments,
{
    arena: ReaderArenaImpl<S, B>,
}

/// Traversal allowance shared by all views of one immutable message.
/// Reopening a borrowed segment provider must not reset this allowance.
pub struct ReadBudget {
    pub(crate) limiter: crate::private::read_limiter::ReadLimiter,
}
impl ReadBudget {
    /// Remaining traversal allowance, or `None` for an unlimited reader.
    /// This is a snapshot; inspecting it does not consume or replenish words.
    #[inline]
    pub fn remaining_words(&self) -> Option<usize> {
        self.limiter.remaining()
    }

    pub fn new(words: Option<usize>) -> Self {
        Self {
            limiter: crate::private::read_limiter::ReadLimiter::new(words),
        }
    }
}

/// Owns a reader and a validated struct root, preserving its traversal budget.
///
/// Checking the root consumes its normal traversal allowance exactly once.
/// Descendants remain lazily checked. Root views borrow this owner; consuming
/// it recovers the original reader, including all budget already consumed.
pub struct CheckedStructReader<S: ReaderSegments> {
    root: layout::CachedStructRoot,
    reader: Reader<S>,
}

/// An owning immutable message selected at a pointer word. Retains no hook table
/// and performs ordinary checked traversal when the application reads its target.
pub struct CheckedPointerReader<S: ReaderSegments> {
    root: layout::CachedPointerRoot,
    reader: Reader<S>,
}
impl<S: ReaderSegments> CheckedPointerReader<S> {
    /// Retain an owning selection with a segment cache refreshed for each
    /// borrow. This does not allocate or reset traversal/nesting allowances.
    /// The reader, including providers with inline storage, can move between
    /// borrows.
    pub fn into_inline_cached(self) -> InlinePointerReader<S> {
        InlinePointerReader {
            root: self.root,
            arena: crate::private::arena::CachedReaderArena::for_borrow(self.reader.arena),
        }
    }
    /// Move this reader into stable shared storage and cache segment zero for
    /// subsequent application reads. This allocates one owner without copying
    /// the message and preserves the existing traversal and nesting budgets.
    /// The cached segment is a snapshot of its extent at conversion; its owner
    /// cannot be recovered or mutated through the returned reader. Other
    /// segments continue to use the original provider. Requires segment zero.
    #[cfg(feature = "alloc")]
    pub fn into_cached(self) -> Result<CachedPointerReader<S>> {
        Ok(CachedPointerReader {
            root: self.root,
            arena: crate::private::arena::CachedReaderArena::owning(self.reader.arena)?,
        })
    }
    /// Borrow the selected pointer without decoding its ancestors again.
    #[inline(always)]
    pub fn root(&self) -> any_pointer::Reader<'_> {
        // SAFETY: selection checked the pointer against its original arena.
        // The cache stores offsets; borrow checks the current extent and uses
        // fresh bases, including after moving an inline segment provider.
        any_pointer::Reader::new(unsafe { self.root.borrow(&self.reader.arena) })
    }
}

/// An owning selected pointer with a segment cache refreshed for each borrow.
/// No extra allocation or pinning is required. Views share the original read
/// budget, and borrowing a view prevents moving its owner until the view expires.
pub struct InlinePointerReader<S: ReaderSegments> {
    root: layout::CachedPointerRoot,
    arena: crate::private::arena::CachedReaderArena<crate::private::arena::OwnedArena<S>>,
}
impl<S: ReaderSegments> InlinePointerReader<S> {
    #[inline(always)]
    pub fn root(&self) -> Result<any_pointer::Reader<'_>> {
        self.arena.refresh_first()?;
        // SAFETY: selection validated these offsets in the same immutable
        // reader. Refresh obtained segment zero from its current owner, including
        // after moves of inline storage. This borrow prevents further moves
        // while the view or its descendants can access the cached descriptor.
        Ok(any_pointer::Reader::new(unsafe {
            self.root.borrow(&self.arena)
        }))
    }
}

/// An owning selected pointer whose segment-zero storage has a stable
/// address. Construct with [`CheckedPointerReader::into_cached`]. Views borrow
/// this owner, and all reads share its original traversal budget.
#[cfg(feature = "alloc")]
pub struct CachedPointerReader<S: ReaderSegments> {
    root: layout::CachedPointerRoot,
    arena: alloc::rc::Rc<
        crate::private::arena::CachedReaderArena<crate::private::arena::OwnedArena<S>>,
    >,
}

/// Shared immutable segments and their original traversal allowance. Selected
/// payloads retain this owner, not a new reader over the same bytes.
#[cfg(feature = "alloc")]
pub struct SharedReader<S: ReaderSegments> {
    arena: alloc::rc::Rc<
        crate::private::arena::CachedReaderArena<crate::private::arena::OwnedArena<S>>,
    >,
}
#[cfg(feature = "alloc")]
impl<S: ReaderSegments> SharedReader<S> {
    pub fn get_root<'a, T: FromPointerReader<'a>>(&'a self) -> Result<T> {
        let root = layout::PointerReader::get_root_from_arena(&*self.arena)?;
        any_pointer::Reader::new(root).get_as()
    }
    /// Retain a pointer from this exact reader, preserving its remaining
    /// nesting depth and sharing the allowance already used by its ancestors.
    pub fn retain(&self, root: any_pointer::Reader<'_>) -> Result<CachedPointerReader<S>> {
        let root = layout::CachedPointerRoot::select(root.reader, &*self.arena)?;
        Ok(CachedPointerReader {
            root,
            arena: self.arena.clone(),
        })
    }
    pub fn size_in_words(&self) -> usize {
        self.arena.size_in_words()
    }
}
#[cfg(feature = "alloc")]
impl<S: ReaderSegments> CachedPointerReader<S> {
    #[inline(always)]
    pub fn root(&self) -> any_pointer::Reader<'_> {
        // SAFETY: selection validated the offsets, and the owning cache retains
        // the same immutable arena at a stable address until every view expires.
        any_pointer::Reader::new(unsafe { self.root.borrow(&*self.arena) })
    }
}

/// An immutable message with one optional selected struct. Dispatchers can
/// cache a view they already decoded without traversing its path a second time.
/// Selection preserves the message's existing traversal and nesting budgets.
pub struct StructReaderCache<S: ReaderSegments> {
    reader: Reader<S>,
    root: core::cell::Cell<Option<layout::CachedStructRoot>>,
}
impl<S: ReaderSegments> StructReaderCache<S> {
    pub fn new(reader: Reader<S>) -> Self {
        Self {
            reader,
            root: core::cell::Cell::new(None),
        }
    }
    pub fn message(&self) -> &Reader<S> {
        &self.reader
    }

    /// Keep an already checked view from this exact message. Foreign views are
    /// rejected; capability tables are not retained. Existing borrowed views
    /// remain valid because neither selection nor reselection changes bytes.
    pub fn select(&self, root: layout::StructReader<'_>) -> Result<()> {
        if !root.belongs_to(&self.reader.arena) {
            return Err(Error::from_kind(ErrorKind::TypeMismatch));
        }
        self.root.set(Some(layout::CachedStructRoot::new(root)?));
        Ok(())
    }
    pub fn get(&self) -> Option<layout::StructReader<'_>> {
        self.root.get().map(|root| {
            // SAFETY: select verified this view belongs to this immutable
            // reader. The cache stores offsets, and borrow obtains fresh bases
            // and checks the extent even for movable/custom segment providers.
            unsafe { root.borrow(&self.reader.arena) }
        })
    }
}

impl<S: ReaderSegments> CheckedStructReader<S> {
    /// Retain an already selected struct using a new owner of the same immutable
    /// segments. Every segment must have the same address and length as in the
    /// source reader; a copy or a partial segment set is rejected. Empty structs
    /// have no segment dependency. Capability tables are not retained.
    ///
    /// This starts an independent traversal budget, charging the selected struct
    /// and one root pointer. Descendants retain normal bounds, traversal and
    /// nesting checks under `options`, without decoding the selector path again.
    #[inline(always)]
    pub fn retain(
        root: layout::StructReader<'_>,
        segments: S,
        options: ReaderOptions,
    ) -> Result<Self> {
        let words = 1
            + (root.get_data_section_size() as usize).div_ceil(64)
            + usize::from(root.get_pointer_section_size());
        let root = layout::CachedStructRoot::retain(root, &segments, options.nesting_limit)?;
        let reader = Reader::new(segments, options);
        reader.arena.amplified_read(words as u64)?;
        Ok(Self { root, reader })
    }

    pub fn new(reader: Reader<S>) -> Result<Self> {
        Self::select(reader, |root| Ok(root))
    }

    /// Cache a selected struct in this message, checking its path once.
    /// The selector must return a view from the supplied reader. Views from
    /// other messages are rejected; capability tables are never retained.
    #[inline(always)]
    pub fn select(
        reader: Reader<S>,
        select: impl for<'a> FnOnce(layout::StructReader<'a>) -> Result<layout::StructReader<'a>>,
    ) -> Result<Self> {
        let root = reader.get_root_internal()?.reader.get_struct(None)?;
        let root = select(root)?;
        if !root.belongs_to(&reader.arena) {
            return Err(crate::Error::from_kind(crate::ErrorKind::TypeMismatch));
        }
        let root = layout::CachedStructRoot::new(root)?;
        Ok(Self { root, reader })
    }

    pub fn root(&self) -> layout::StructReader<'_> {
        // SAFETY: the cache contains only offsets into this exact reader's
        // validated segments. Moving the reader (including inline segments)
        // preserves their bytes and lengths; borrow derives fresh pointers from
        // their current addresses. No mutable access or capability table escapes.
        unsafe { self.root.borrow(&self.reader.arena) }
    }

    pub fn into_reader(self) -> Reader<S> {
        self.reader
    }
}

impl<S> Reader<S>
where
    S: ReaderSegments,
{
    pub fn new(segments: S, options: ReaderOptions) -> Self {
        Self {
            arena: ReaderArenaImpl::new(segments, options),
        }
    }

    /// Select a pointer while consuming its immutable segment owner. The
    /// selector may decline without producing a cache. A selected pointer must
    /// belong to the supplied root's arena (or be a default/null reader).
    /// Selection preserves this reader's consumed traversal budget and the
    /// selected pointer's remaining nesting depth. Offsets survive owner moves.
    #[inline(always)]
    pub fn try_select_pointer<T, E: From<Error>>(
        self,
        select: impl for<'a> FnOnce(
            any_pointer::Reader<'a>,
        )
            -> core::result::Result<Option<(any_pointer::Reader<'a>, T)>, E>,
    ) -> core::result::Result<Option<(CheckedPointerReader<S>, T)>, E> {
        self.try_select_pointer_or_else(select, drop)
    }

    /// Like `try_select_pointer`, but returns the original owner to `recover`
    /// whenever selection declines or fails. Recovery preserves consumed read
    /// limits, including failures while checking the selected pointer's arena.
    #[inline(always)]
    pub fn try_select_pointer_or_else<T, E: From<Error>>(
        self,
        select: impl for<'a> FnOnce(
            any_pointer::Reader<'a>,
        )
            -> core::result::Result<Option<(any_pointer::Reader<'a>, T)>, E>,
        recover: impl FnOnce(Self),
    ) -> core::result::Result<Option<(CheckedPointerReader<S>, T)>, E> {
        let selected = (|| {
            let arena = self.arena.cached()?;
            let pointer = layout::PointerReader::get_root_from_arena(&arena)?;
            let Some((selected, value)) = select(any_pointer::Reader::new(pointer))? else {
                return Ok(None);
            };
            let root = layout::CachedPointerRoot::select(selected.reader, &arena)?;
            Ok(Some((root, value)))
        })();
        match selected {
            Ok(Some((root, value))) => {
                Ok(Some((CheckedPointerReader { root, reader: self }, value)))
            }
            Ok(None) => {
                recover(self);
                Ok(None)
            }
            Err(error) => {
                recover(self);
                Err(error)
            }
        }
    }

    pub fn into_typed<T: Owned>(self) -> TypedReader<S, T> {
        TypedReader::new(self)
    }

    /// Move the original arena into shared storage without resetting limits.
    #[cfg(feature = "alloc")]
    pub fn into_shared(self) -> Result<SharedReader<S>> {
        Ok(SharedReader {
            arena: crate::private::arena::CachedReaderArena::owning(self.arena)?,
        })
    }
    /// Open segments against an externally owned traversal allowance.
    pub fn with_budget(
        segments: S,
        options: ReaderOptions,
        budget: &ReadBudget,
    ) -> Reader<S, &ReadBudget> {
        Reader {
            arena: ReaderArenaImpl::with_budget(segments, options, budget),
        }
    }
}

impl<S: ReaderSegments, B: core::borrow::Borrow<ReadBudget>> Reader<S, B> {
    #[inline(always)]
    fn get_root_internal(&self) -> Result<any_pointer::Reader<'_>> {
        let pointer_reader = layout::PointerReader::get_root_from_arena(&self.arena)?;
        Ok(any_pointer::Reader::new(pointer_reader))
    }

    /// Gets the root of the message, interpreting it as the given type.
    #[inline(always)]
    pub fn get_root<'a, T: FromPointerReader<'a>>(&'a self) -> Result<T> {
        self.get_root_internal()?.get_as()
    }

    /// Inspect this message through a short-lived arena which caches segment
    /// zero. The callback cannot return readers borrowing that arena. It shares
    /// this reader's traversal budget, and far pointers use the original owner.
    pub fn with_root<R>(
        &self,
        read: impl for<'a> FnOnce(any_pointer::Reader<'a>) -> R,
    ) -> Result<R> {
        let arena = self.arena.cached()?;
        let pointer = layout::PointerReader::get_root_from_arena(&arena)?;
        Ok(read(any_pointer::Reader::new(pointer)))
    }

    /// The authoritative traversal allowance shared by all views of this reader.
    pub fn read_budget(&self) -> &ReadBudget {
        self.arena.read_budget()
    }

    pub fn into_segments(self) -> S {
        self.arena.into_segments()
    }

    /// Checks whether the message is [canonical](https://capnproto.org/encoding.html#canonicalization).
    pub fn is_canonical(&self) -> Result<bool> {
        let (segment_start, seg_len) = self.arena.get_segment(0)?;

        if self.arena.get_segment(1).is_ok() {
            // TODO(cleanup, apibump): should there be a nicer way to ask the arena how many
            // segments there are?

            // There is more than one segment, so the message cannot be canonical.
            return Ok(false);
        }

        let pointer_reader = unsafe {
            layout::PointerReader::get_root(
                &self.arena,
                0,
                segment_start,
                self.arena.nesting_limit(),
            )
        }?;
        let read_head = ::core::cell::Cell::new(unsafe { segment_start.add(BYTES_PER_WORD) });
        let root_is_canonical = pointer_reader.is_canonical(&read_head)?;
        let all_words_consumed = (read_head.get() as usize - segment_start as usize)
            / BYTES_PER_WORD
            == seg_len as usize;
        Ok(root_is_canonical && all_words_consumed)
    }

    /// Gets the [canonical](https://capnproto.org/encoding.html#canonicalization) form
    /// of this message. Works by copying the message twice. For a canonicalization
    /// method that only requires one copy, see `message::Builder::set_root_canonical()`.
    #[cfg(feature = "alloc")]
    pub fn canonicalize(&self) -> Result<alloc::vec::Vec<crate::Word>> {
        let root = self.get_root_internal()?;
        let size = root.target_size()?.word_count + 1;
        let mut message =
            Builder::new(HeapAllocator::new().first_segment_words(u32::try_from(size).unwrap()));
        message.set_root_canonical(root)?;
        let output_segments = message.get_segments_for_output();
        assert_eq!(1, output_segments.len());
        let output = output_segments[0];
        assert!((output.len() / BYTES_PER_WORD) as u64 <= size);
        let mut result = crate::Word::allocate_zeroed_vec(output.len() / BYTES_PER_WORD);
        crate::Word::words_to_bytes_mut(&mut result[..]).copy_from_slice(output);
        Ok(result)
    }

    pub fn size_in_words(&self) -> usize {
        self.arena.size_in_words()
    }

    /// Retrieves the underlying [`ReaderSegments`] object.
    pub fn get_segments(&self) -> &S {
        self.arena.get_segments()
    }
}

/// A message reader whose value is known to be of type `T`.
/// Please see [module documentation](self) for more info about reader type specialization.
